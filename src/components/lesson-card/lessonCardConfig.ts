const BASE_TIMES: Record<string, number[]> = {
  "45": [2, 5, 20, 13, 5],
  "90": [3, 10, 35, 32, 10],
};

export const makeDefaultStages = (duration: string): Stage[] => {
  const times = BASE_TIMES[duration] || BASE_TIMES["45"];
  return BASE_STAGES.map((s, i) => ({ ...s, id: newStageId(), time: times[i] }));
};
